"""Independent check of the answers in subjects/math/trigonometry."""
from math import pi, sin, cos, tan, sqrt, radians, degrees, acos, isclose
res = []
ok = lambda c, m: res.append(c) or print(('ok   ' if c else 'FAIL ') + m)
eq = lambda a, b: isclose(a, b, abs_tol=1e-9)
ok(all(eq(radians(d), r) for d, r in [(180, pi), (90, pi/2), (60, pi/3), (45, pi/4), (30, pi/6), (120, 2*pi/3)]), '1.1 deg->rad')
ok([round(degrees(x)) for x in (3*pi/4, 5*pi/6, 3*pi/2)] == [135, 150, 270], '1.1 rad->deg')
sg = lambda v: 'p' if v > 0 else 'm'
exp = {pi/3: 'ppp', 2*pi/3: 'pmm', 4*pi/3: 'mmp', 5*pi/3: 'mpm'}
ok(all(sg(sin(a)) + sg(cos(a)) + sg(tan(a)) == e for a, e in exp.items()), '1.2 signs')
ok(eq(pi/3*2, 2*pi/3) and eq(0.5*(2*pi/3)*2, 2*pi/3), '1.3 arc and sector')
ok(all(eq(sin(a)**2, s) and eq(cos(a)**2, c) for a, s, c in [(pi/6, 1/4, 3/4), (pi/4, 1/2, 1/2), (pi/3, 3/4, 1/4), (2*pi/3, 3/4, 1/4)]), '2.1')
a = pi - __import__('math').asin(3/5)
ok(eq(cos(a)**2, 16/25) and eq(cos(a), -4/5) and eq(tan(a), -3/4), '2.2')
a = __import__('math').atan(2); ok(eq((sin(a) + cos(a)) / (sin(a) - cos(a)), 3), '2.3')
al = pi/6; s, c = sin(al), cos(al)
ok(eq(sin(pi - al), s) and eq(sin(pi-al), 1/2), '2.4 sin(pi-a)')
ok(eq(cos(pi - al), -c) and eq(cos(pi-al), -sqrt(3)/2), '2.4 cos(pi-a)')
ok(eq(sin(pi + al), -s) and eq(sin(pi+al), -1/2), '2.4 sin(pi+a)')
ok(eq(sin(-al), -s), '2.4 sin(-a)')
ok(eq(cos(pi/2 - al), s) and eq(cos(pi/2-al), 1/2), '2.4 cos(pi/2-a)')
ok(eq(sin(pi/2 + al), c) and eq(sin(pi/2+al), sqrt(3)/2), '2.4 sin(pi/2+a)')
ok(abs(1/2 + sqrt(3)/2 - 1.37) < 0.005, '3.1 approx 1.37')
ok(eq(sin(radians(75)), (sqrt(6)+sqrt(2))/4) and eq(cos(radians(75)), (sqrt(6)-sqrt(2))/4), '3.2')
a = pi - __import__('math').asin(3/5); ok(eq(sin(2*a), -24/25) and eq(cos(2*a), 7/25), '3.3')
xs = [i/1000 for i in range(0, 6284)]
ok(all(eq(sin(x) + sqrt(3)*cos(x), 2*sin(x + pi/3)) for x in xs[::50]), '3.4 aux angle')
ok(isclose(max(sin(x)+sqrt(3)*cos(x) for x in xs), 2, abs_tol=1e-5), '3.4 max 2')
ok(all(eq(sin(x)*cos(x), sin(x+pi)*cos(x+pi)) for x in xs[::97]) and not all(eq(sin(x)*cos(x), sin(x+pi/2)*cos(x+pi/2)) for x in xs[1::97]), '3.4 period pi')
ok(isclose(max(sin(x)*cos(x) for x in xs), 0.5, abs_tol=1e-5), '3.4 max 1/2')
ok(eq(sin(5*pi/6 - pi/3), 1), '4.1 peak 5pi/6')
ok(all(eq(sin(2*x + pi/3), sin(2*(x + pi/6))) for x in xs[::100]), '4.2 left pi/6')
f = lambda x: 3*sin(2*x - pi/4) + 1
ok(eq(f(3*pi/8), 4) and isclose(min(f(x) for x in xs), -2, abs_tol=1e-4), '4.3')
ok(all(eq(f(x), f(x+pi)) for x in xs[::120]), '4.3 period pi')
ok(eq(1/sin(radians(30)), 2) and eq(sqrt(3)/sin(radians(60)), 2) and eq(2/sin(radians(90)), 2), '5.1 row 1')
ok(eq(1/sin(radians(45)), sqrt(2)) and eq(sqrt(2)/1, sqrt(2)), '5.1 row 2')
for (a_, b_, C, c_, s2, c2, d, k) in [(3, 4, 90, 5, 25, 25, 0, 0), (1, 1, 60, 1, 2, 1, 1, 1), (1, 1, 120, sqrt(3), 2, 3, -1, -1)]:
    ok(eq(a_*a_ + b_*b_, s2) and eq(c_*c_, c2) and eq(s2 - c2, d) and eq(2*a_*b_*cos(radians(C)), k) and eq(c_*c_, a_*a_ + b_*b_ - 2*a_*b_*cos(radians(C))), f'5.2 row C={C}')
ok(eq(9 + 25 - 2*15*cos(2*pi/3), 49), '5.3a')
ok(eq((9 + 25 - 49)/30, -1/2) and eq(acos(-1/2), 2*pi/3), '5.3b')
ok(eq(2*sin(pi/3)/sin(pi/4), sqrt(6)), '5.3c')
ok(eq(0.5*4*5*sin(pi/6), 5), '5.3d')
a = pi - __import__('math').asin(4/5); ok(eq(tan(a), -4/3), 'exam 2')
a = __import__('math').atan(3); ok(eq((sin(a)+cos(a))/(sin(a)-cos(a)), 2), 'exam 3')
a = __import__('math').asin(1/3); ok(eq(cos(pi/2 + a), -1/3), 'exam 4')
ok(eq(sin(radians(15))*cos(radians(15)), 1/4), 'exam 5')
ok(eq(cos(pi/8)**2 - sin(pi/8)**2, sqrt(2)/2), 'exam 6')
ok(eq(acos((9+25-49)/30), 2*pi/3), 'exam 10')
ok(eq(sin(radians(45))/sin(radians(30)), sqrt(2)), 'exam 11')
ok(eq(0.5*2*3*sin(radians(60)), 3*sqrt(3)/2), 'exam 12')
print('ALL OK' if all(res) else 'SOME FAILED')
